const TARGET_LOCALES = ["he","ru","ar","fr","es","de"];

function apply() {
  const updated = [];
  for (const locale of TARGET_LOCALES) {
    const filePath = path.join(localesDir, `${locale}.json`);
    if (!fs.existsSync(filePath)) {
      throw new Error(`Missing locale file: ${filePath}`);
    }
    const bundle = JSON.parse(fs.readFileSync(filePath, "utf8"));
    const t = TRANSLATIONS[locale];
    if (!t?.useCaseShared || !t?.useCases) {
      throw new Error(`Missing translations for locale: ${locale}`);
    }
    bundle.useCaseShared = t.useCaseShared;
    bundle.useCases = t.useCases;
    fs.writeFileSync(filePath, `${JSON.stringify(bundle, null, 2)}\n`, "utf8");
    updated.push(locale);
  }
  return updated;
}

